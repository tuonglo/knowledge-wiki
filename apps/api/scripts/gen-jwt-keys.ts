/**
 * Generates an RS256 key pair for signing access tokens and appends it to the
 * repo-root .env as base64-encoded PEM (one line each, so any .env reader copes).
 *
 *   pnpm --filter @kw/api gen:keys
 *
 * Never prints the private key. Refuses to overwrite existing keys, since that
 * would invalidate every token already issued (= log everyone out).
 */
import { generateKeyPairSync } from "node:crypto";
import { appendFileSync, existsSync, readFileSync } from "node:fs";
import { resolve } from "node:path";

const envPath = resolve(import.meta.dirname, "../../../.env");
const current = existsSync(envPath) ? readFileSync(envPath, "utf8") : "";

if (/^JWT_PRIVATE_KEY=.+/m.test(current)) {
  console.error(`JWT keys already exist in ${envPath}. Delete those lines first to replace them.`);
  process.exit(1);
}

const { privateKey, publicKey } = generateKeyPairSync("rsa", {
  modulusLength: 2048,
  privateKeyEncoding: { type: "pkcs8", format: "pem" },
  publicKeyEncoding: { type: "spki", format: "pem" },
});

const b64 = (pem: string) => Buffer.from(pem).toString("base64");
const block = [
  "",
  "# Access-token signing keys (RS256, base64-encoded PEM). Generated by `pnpm --filter @kw/api gen:keys`.",
  "# The private key stays in the API only; services that just verify get the public key.",
  `JWT_PRIVATE_KEY=${b64(privateKey)}`,
  `JWT_PUBLIC_KEY=${b64(publicKey)}`,
  "",
].join("\n");

appendFileSync(envPath, (current.endsWith("\n") || current === "" ? "" : "\n") + block);
console.log(`Added JWT_PRIVATE_KEY and JWT_PUBLIC_KEY to ${envPath}`);
